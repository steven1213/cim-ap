-- RMS W9/W10/W11（MySQL 变体，字段与 h2 版本一一对应）。

CREATE TABLE rms_notification (
    id              VARCHAR(64)  NOT NULL,
    description     VARCHAR(512),
    version         BIGINT,
    deleted         TINYINT(1)   NOT NULL DEFAULT 0,
    create_time     DATETIME,
    event_time      DATETIME,
    create_user     VARCHAR(64),
    event_user      VARCHAR(64),
    event_name      VARCHAR(128),
    event_comment   VARCHAR(512),
    trx_id          VARCHAR(64),
    tenant_id       VARCHAR(64),
    type            VARCHAR(48)  NOT NULL,
    title           VARCHAR(128) NOT NULL,
    content         VARCHAR(512),
    recipient       VARCHAR(64),
    audience        VARCHAR(32),
    ref_type        VARCHAR(32),
    ref_id          VARCHAR(64),
    occurred_at     DATETIME     NOT NULL,
    PRIMARY KEY (id),
    KEY idx_noti_recipient (recipient),
    KEY idx_noti_audience (audience),
    KEY idx_noti_occurred (occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE rms_notification_read (
    id              VARCHAR(64)  NOT NULL,
    description     VARCHAR(512),
    version         BIGINT,
    deleted         TINYINT(1)   NOT NULL DEFAULT 0,
    create_time     DATETIME,
    event_time      DATETIME,
    create_user     VARCHAR(64),
    event_user      VARCHAR(64),
    event_name      VARCHAR(128),
    event_comment   VARCHAR(512),
    trx_id          VARCHAR(64),
    tenant_id       VARCHAR(64),
    notification_id VARCHAR(64)  NOT NULL,
    username        VARCHAR(64)  NOT NULL,
    read_at         DATETIME     NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_noti_read (notification_id, username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE rms_body_template (
    id                   VARCHAR(64)  NOT NULL,
    description          VARCHAR(512),
    version              BIGINT,
    deleted              TINYINT(1)   NOT NULL DEFAULT 0,
    create_time          DATETIME,
    event_time           DATETIME,
    create_user          VARCHAR(64),
    event_user           VARCHAR(64),
    event_name           VARCHAR(128),
    event_comment        VARCHAR(512),
    trx_id               VARCHAR(64),
    tenant_id            VARCHAR(64),
    code                 VARCHAR(64)  NOT NULL,
    name                 VARCHAR(128) NOT NULL,
    body_format          VARCHAR(32)  NOT NULL,
    scope_device_type_id VARCHAR(64),
    enforced             TINYINT(1)   NOT NULL DEFAULT 1,
    template_body        LONGTEXT,
    PRIMARY KEY (id),
    UNIQUE KEY uk_btpl_code (code),
    KEY idx_btpl_scope (scope_device_type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE rms_body_template_item (
