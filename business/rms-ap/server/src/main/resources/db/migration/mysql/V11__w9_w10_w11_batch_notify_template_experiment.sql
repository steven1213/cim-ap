CREATE TABLE rms_experiment (
    id            VARCHAR(64)  NOT NULL,
    description   VARCHAR(512),
    version       BIGINT,
    deleted       TINYINT(1)   NOT NULL DEFAULT 0,
    create_time   DATETIME,
    event_time    DATETIME,
    create_user   VARCHAR(64),
    event_user    VARCHAR(64),
    event_name    VARCHAR(128),
    event_comment VARCHAR(512),
    trx_id        VARCHAR(64),
    tenant_id     VARCHAR(64),
    code          VARCHAR(64)  NOT NULL,
    recipe_id     VARCHAR(64)  NOT NULL,
    recipe_code   VARCHAR(128),
    version_id    VARCHAR(64)  NOT NULL,
    version_no    INT,
    device_id     VARCHAR(64)  NOT NULL,
    device_code   VARCHAR(128),
    reason        VARCHAR(512),
    status        VARCHAR(32)  NOT NULL,
    requested_by  VARCHAR(64),
    decided_by    VARCHAR(64),
    decided_at    DATETIME,
    valid_from    DATETIME,
    valid_until   DATETIME     NOT NULL,
    closed_at     DATETIME,
    close_reason  VARCHAR(512),
    PRIMARY KEY (id),
    UNIQUE KEY uk_exp_code (code),
    KEY idx_exp_device (device_id),
    KEY idx_exp_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

